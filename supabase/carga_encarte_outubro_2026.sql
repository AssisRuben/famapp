-- 1) Campanha (cartazetes, desempenho e .txt da Trier)
with camp as (
  insert into campanhas (nome, data_inicio, data_fim)
  values ('Encarte outubro', date '2026-10-01', date '2026-10-15')
  returning id
),
prod as (
  -- mesmo EAN em 2 cadastros (irmãos) -> os dois entram
  select distinct on (pc.codigo) pc.codigo, t.preco, pc.preco_venda
  from tmp_encarte t
  join produto_catalogo pc on pc.codigo_barras = t.ean
  order by pc.codigo, t.preco
)
insert into campanha_produtos (campanha_id, codigo_produto, preco_promocional, percentual_desconto)
select camp.id, prod.codigo, prod.preco,
       coalesce(greatest(0, least(99.99, round((1 - prod.preco / nullif(prod.preco_venda, 0)) * 100, 2))), 0)
from camp, prod;

-- 2) Venda adicional: ranking por quantidade de itens no período,
--    prêmios 250/150/100, só concorre quem vender 11+ ("acima de 10")
with va as (
  insert into campanhas_venda_adicional
    (nome, data_inicio, data_fim, tipo_premiacao, premiacao_ranking, minimo_para_concorrer, criterio_quantidade)
  values (
    'Encarte outubro', date '2026-10-01', date '2026-10-15', 'ranking',
    '[{"posicao":1,"valor":250},{"posicao":2,"valor":150},{"posicao":3,"valor":100}]'::jsonb,
    11, 'acumulado_periodo'
  )
  returning id
)
insert into campanha_venda_adicional_produtos (campanha_id, codigo_produto)
select distinct va.id, pc.codigo
from va, tmp_encarte t
join produto_catalogo pc on pc.codigo_barras = t.ean;

