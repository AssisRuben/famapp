-- Conferência: totais + EANs do encarte que NÃO estão no cadastro
select 'RESUMO' as tipo,
       (select count(*) from tmp_encarte)::text as ean,
       'produtos na campanha: ' || (select count(*) from campanha_produtos cp join campanhas c on c.id = cp.campanha_id
                                     where c.nome = 'Encarte outubro' and c.data_inicio = date '2026-10-01')
       || ' | na venda adicional: ' || (select count(*) from campanha_venda_adicional_produtos p
                                     join campanhas_venda_adicional c on c.id = p.campanha_id
                                     where c.nome = 'Encarte outubro' and c.data_inicio = date '2026-10-01') as nome
union all
select 'SEM CADASTRO', t.ean, t.nome
from tmp_encarte t
where not exists (select 1 from produto_catalogo pc where pc.codigo_barras = t.ean)
order by 1 desc, 3;
