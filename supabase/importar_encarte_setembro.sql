    campanha_id, codigo_produto, preco_promocional, percentual_desconto, quantidade_cartazes, tipo_promocao
  )
  select
    v_campanha_id,
    pc.codigo,
    e.preco_promocional,
    greatest(0, round(((pc.preco_venda - e.preco_promocional) / nullif(pc.preco_venda, 0)) * 100, 2)),
    1,
    'unitario'
  from _encarte_setembro e
  join produto_catalogo pc on pc.codigo_barras = e.codigo_barras
  on conflict (campanha_id, codigo_produto) do nothing;

  select string_agg('  ' || e.codigo_barras || ' - ' || e.nome_planilha, E'
')
  into v_nao_encontrados_lista
  from _encarte_setembro e
  where not exists (select 1 from produto_catalogo pc where pc.codigo_barras = e.codigo_barras);

  raise notice 'Campanha "%" criada (id=%). Produtos inseridos: %.',
    'ENCARTE SETEMBRO', v_campanha_id,
